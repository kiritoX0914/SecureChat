// Interop vector generator / verifier for PROTOCOL.md (uses the app's real crypto code).
// gen <out.json>          : B publishes bundle, A runs X3DH and sends 3 messages + a file
// verify <py_out.json>    : A (restored from UserDefaults) decrypts Python-produced replies
import Foundation
import CryptoKit

let A_ID = "A1111111-1111-1111-1111-111111111111"
let B_ID = "B2222222-2222-2222-2222-222222222222"
let ud = UserDefaults.standard
func b64(_ d: Data) -> String { d.base64EncodedString() }
func fail(_ s: String) -> Never { print("FAIL: \(s)"); exit(1) }

let args = CommandLine.arguments
guard args.count >= 3 else { fail("usage") }

if args[1] == "gen" {
    for k in ud.dictionaryRepresentation().keys where k.hasPrefix("sc.") { ud.removeObject(forKey: k) }
    // --- B (responder) ---
    let B = CryptoEngine(deviceId: B_ID)
    var bundle = B.generatePreKeyBundle()
    bundle.protocolVersion = 2
    bundle.hasSession = false
    let helloEnv = try! WireEnvelope.make(type: .hello, senderId: B_ID, senderName: "Bob", payload: bundle)
    let bIdentityDH = ud.data(forKey: "sc.identity.dh")!
    let bIdentitySig = ud.data(forKey: "sc.identity.signing")!
    let spkJSON = try! JSONSerialization.jsonObject(with: ud.data(forKey: "sc.signedPreKey")!) as! [String: Any]
    for k in ud.dictionaryRepresentation().keys where k.hasPrefix("sc.") { ud.removeObject(forKey: k) }

    // --- A (initiator, smaller id) ---
    let A = CryptoEngine(deviceId: A_ID)
    try! A.processReceivedBundle(bundle, from: B_ID)
    var frames: [String] = []
    var plaintexts: [String] = []
    let inner = try! JSONEncoder().encode(InnerEnvelope(v: 2, control: ControlMessage(kind: .sessionInit)))
    var msgs: [Data] = [inner]
    for (i, t) in ["hello from swift A", "second message 🎉", "third"].enumerated() {
        var m = ChatMessage(id: UUID(), senderId: A_ID, recipientId: B_ID, text: t,
                            timestamp: Date(timeIntervalSinceReferenceDate: 784_000_000 + Double(i)), status: .sent)
        m.senderName = "Alice"
        if i == 1 { m.replyToId = UUID(); m.replyToText = "quoted"; m.replyToSender = "Bob" }
        msgs.append(try! JSONEncoder().encode(m))
    }
    for p in msgs {
        let (isPre, payload) = try! A.encrypt(p, for: B_ID)
        let env = WireEnvelope(type: isPre ? .preKeyMessage : .message, senderId: A_ID, senderName: "Alice", payload: payload)
        frames.append(b64(try! env.wireData()))
        plaintexts.append(String(data: p, encoding: .utf8)!)
    }
    // --- file chunks (same calls as FileTransferEngine) ---
    var file = Data(count: 150_000)
    for i in 0..<file.count { file[i] = UInt8((i * 31 + 7) & 0xFF) }
    let key = SymmetricKey(size: .bits256)
    let tid = UUID()
    let total = UInt32((file.count + 65535) / 65536)
    var chunks: [String] = []
    for i in 0..<Int(total) {
        let part = file.subdata(in: (i * 65536)..<min(file.count, (i + 1) * 65536))
        let aad = FileChunkFrame.aad(transferId: tid, index: UInt32(i), total: total)
        let box = try! AES.GCM.seal(part, using: key, authenticating: aad).combined!
        chunks.append(b64(FileChunkFrame.encode(transferId: tid, index: UInt32(i), total: total, box: box)))
    }
    ud.synchronize()
    let out: [String: Any] = [
        "note": "Generated by the Swift app crypto. B's private keys are included so other implementations can play B.",
        "A": ["deviceId": A_ID],
        "B": ["deviceId": B_ID,
              "identityDHPrivate": b64(bIdentityDH),
              "identitySigningPrivate": b64(bIdentitySig),
              "signedPreKeyId": spkJSON["id"]!,
              "signedPreKeyPrivate": spkJSON["keyPairData"]!,
              "helloFrame": b64(try! helloEnv.wireData())],
        "aToB": frames,
        "aToBPlaintexts": plaintexts,
        "file": ["transferId": tid.uuidString, "key": b64(key.withUnsafeBytes { Data($0) }),
                 "sha256": SHA256.hash(data: file).map { String(format: "%02x", $0) }.joined(),
                 "size": file.count, "chunkFrames": chunks],
    ]
    try! JSONSerialization.data(withJSONObject: out, options: [.prettyPrinted, .sortedKeys])
        .write(to: URL(fileURLWithPath: args[2]))
    print("gen ok: \(frames.count) frames, \(chunks.count) chunks")
} else {
    let A = CryptoEngine(deviceId: A_ID)
    guard A.hasSession(for: B_ID) else { fail("A session not restored") }
    let obj = try! JSONSerialization.jsonObject(with: Data(contentsOf: URL(fileURLWithPath: args[2]))) as! [String: Any]
    let frames = obj["bToA"] as! [String]
    let expected = obj["bToAText"] as! [String]
    for (i, f) in frames.enumerated() {
        let env = try! JSONDecoder().decode(WireEnvelope.self, from: Data(base64Encoded: f)!)
        guard env.type == .message, env.senderId == B_ID else { fail("envelope \(i) header") }
        let enc = try! env.decodePayload(EncryptedMessagePayload.self)
        let plain: Data
        do { plain = try A.decryptMessage(enc, from: B_ID) } catch { fail("decrypt python msg \(i): \(error)") }
        if let m = try? JSONDecoder().decode(ChatMessage.self, from: plain) {
            guard m.text == expected[i] else { fail("text \(i): \(m.text)") }
            print("swift decrypted python ChatMessage \(i): \(m.text) ts=\(m.timestamp) reply=\(m.replyToId?.uuidString ?? "-")")
        } else if let c = try? JSONDecoder().decode(InnerEnvelope.self, from: plain) {
            guard c.control.kind.rawValue == expected[i] else { fail("control \(i)") }
            print("swift decrypted python control \(i): \(c.control.kind) name=\(c.control.name ?? "-")")
        } else { fail("plaintext \(i) not decodable: \(String(data: plain, encoding: .utf8) ?? "?")") }
    }
    let f = obj["file"] as! [String: Any]
    let key = SymmetricKey(data: Data(base64Encoded: f["key"] as! String)!)
    var data = Data()
    for c in f["chunkFrames"] as! [String] {
        guard let ch = FileChunkFrame.decode(Data(base64Encoded: c)!) else { fail("chunk decode") }
        let aad = FileChunkFrame.aad(transferId: ch.transferId, index: ch.index, total: ch.total)
        guard let plain = try? AES.GCM.open(try AES.GCM.SealedBox(combined: ch.box), using: key, authenticating: aad) else { fail("chunk open") }
        data.append(plain)
    }
    let sha = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    guard sha == f["sha256"] as! String else { fail("file sha") }
    print("swift decrypted python file chunks ok (\(data.count) bytes)")
    print("VERIFY OK")
}
